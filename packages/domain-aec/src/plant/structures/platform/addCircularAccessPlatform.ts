import { defineCommand, z } from '@core/commands/schema';
import type { CommandResult } from '@core/commands/types';
import { fromMm } from '@core/model/units';
import type { AssemblyElement } from '@aec/building/types';
import { appendElements, getBuilding } from '../../../building/model';
import { refuse } from '../codes';
import { vesselOf } from './circularBuild';
import { generate } from './platformRegenerate';
import { commitPlatform, refusal } from './platformCommit';
import { railingFieldParams, resolveRailingFields } from './platformRailing';
import type { CircularSpec } from './platformSpec';

const DEFAULT_BRACKET_PROFILE = 'UPN160';
const DEFAULT_CIRCULAR_GRATING = '19-W-4 1-1/4x3/16';
const DEFAULT_GAP_MM = 50;
const DEFAULT_CIRCULAR_EDGES: CircularEdges = ['outer', 'ends'];

type CircularEdges = Array<'outer' | 'inner' | 'ends'>;

export const circularRailingParam = z
  .object({
    edges: z
      .array(z.enum(['outer', 'inner', 'ends']))
      .min(1)
      .optional()
      .describe('"outer" arc, "inner" arc (vessel side) and/or the two radial "ends" (a full circle has none). Default ["outer", "ends"].'),
    ...railingFieldParams,
  })
  .describe(
    'Guard-rails (omit for none). Their posts stand at equal chords <= postSpacingMax along the arc. Unset values follow the rulesets, as in add_railing, and are named in data.defaults.',
  );

/**
 * @affects creates 1 assembly element (mark AS<n>, hostId = the vessel) plus brackets (role bracket), one grating segment per bracket bay and guard-rails, all with assemblyId
 * @invariant ri = OD / 2 + gap, ro = ri + width; nb = ceil(sweep x ro / spacing) + 1 brackets (a full circle shares the first and last); the segments tile the sector; the parts are read-only and regenerated by update_access_platform
 * @failure unknown equipment -> STA_UNKNOWN_ELEMENT; not a vertical vessel -> STA_EQUIPMENT_NOT_VESSEL; elevation outside 0..height -> STA_OUTSIDE_SHELL; unknown type / profile -> STA_GRATING_TYPE_UNKNOWN / STA_INVALID_GEOMETRY; overlap at the same elevation -> STA_PLATFORM_OVERLAP
 */
export const addCircularAccessPlatform = defineCommand({
  name: 'add_circular_access_platform',
  description:
    'Generate a circular (annular-sector) access platform around a VERTICAL VESSEL (add_equipment shape vertical_vessel): radial bracket cantilevers welded to the shell, grating segments between them and guard-rails, in ONE step. ' +
    'All lengths in DOCUMENT UNITS, angles in DEGREES counter-clockwise from +X. `elevation` = walking-surface height above the level elevation of the vessel (0 < elevation <= vessel height). ' +
    'Radii: ri = vessel diameter / 2 + gap (default 50 mm), ro = ri + width; the sector runs from `startAngleDeg` (default 0) over `sweepDeg` (default 360, a full ring). ' +
    'Brackets: nb = ceil(sweep x ro / bracketSpacingMax) + 1 (a full ring shares the first and last), UPN160 by default. Without bracketSpacingMax the step is 8 deg (every bracket within 4 deg of perpendicular to the bars of its panels), so check_grating accepts the supports; a larger spacing is accepted, but then check_grating reports STA_GRATING_SPAN_DIRECTION for the skewed panels (the skew is in data.notes). ' +
    '`railing` adds guard-rails on "outer", "inner" and/or "ends" (default outer + ends). The platform follows the vessel: after update_equipment or a move, run update_access_platform { assemblyId } to re-derive it (access_platform_takeoff reports stale: true). ' +
    'The parts are derived and read-only (CMD_DERIVED_GEOMETRY); delete the platform with delete_building_element on the assembly. Result data: assemblyId, partIds, memberIds, gratingIds, railingIds, quantities (radii, arcs, sector area, kg), notes, defaults.',
  params: z.object({
    equipmentId: z.string().describe('Id of the vertical vessel (equipment element) the platform surrounds.'),
    elevation: z
      .number()
      .describe('Walking-surface height above the vessel level elevation, DOCUMENT UNITS; 0 < elevation <= the vessel height.'),
    width: z.number().positive().describe('Radial width of the walkway, DOCUMENT UNITS (ro - ri).'),
    startAngleDeg: z.number().optional().describe('Start of the sector, degrees counter-clockwise from +X. Default 0.'),
    sweepDeg: z.number().positive().max(360).optional().describe('Angular extent, degrees, 0 < sweep <= 360. Default 360 (full ring).'),
    gap: z.number().min(0).optional().describe('Clear gap between the shell and the walkway, DOCUMENT UNITS. Default 50 mm.'),
    gratingType: z.string().optional().describe('Catalogue key from list_grating_types. Default "19-W-4 1-1/4x3/16".'),
    bracketProfile: z.string().optional().describe('Steel catalogue name of the brackets (list_steel_profiles). Default UPN160.'),
    bracketSpacingMax: z
      .number()
      .positive()
      .optional()
      .describe(
        'Largest arc distance between brackets at the outer radius, DOCUMENT UNITS. Default: 8 deg steps (bars within 4 deg of perpendicular to the brackets).',
      ),
    railing: circularRailingParam.optional(),
  }),
  run: (doc, params): CommandResult => {
    const building = getBuilding(doc);
    const vessel = vesselOf(building, params.equipmentId);
    if ('ok' in vessel) return refusal(doc, 'add_circular_access_platform', vessel);
    const defaults: string[] = [];
    const named = <Value>(value: Value | undefined, fallback: Value, basis: string): Value => {
      if (value === undefined) defaults.push(basis);
      return value ?? fallback;
    };
    let railing: CircularSpec['railing'] = null;
    if (params.railing !== undefined) {
      const { edges, ...input } = params.railing;
      const fields = resolveRailingFields(doc, input, defaults);
      if (typeof fields === 'string') return refuse(doc, 'add_circular_access_platform', 'STA_INVALID_GEOMETRY', fields, [], ['railing']);
      railing = { edges: named(edges, DEFAULT_CIRCULAR_EDGES, 'railing edges outer + ends'), ...fields };
    }
    const spec: CircularSpec = {
      kind: 'circular_platform',
      equipmentId: params.equipmentId,
      elevation: params.elevation,
      startAngleDeg: named(params.startAngleDeg, 0, 'startAngleDeg 0'),
      sweepDeg: named(params.sweepDeg, 360, 'sweepDeg 360 (full ring)'),
      gap: named(params.gap, fromMm(doc, DEFAULT_GAP_MM), `gap ${DEFAULT_GAP_MM} mm`),
      width: params.width,
      gratingType: named(params.gratingType, DEFAULT_CIRCULAR_GRATING, `gratingType ${DEFAULT_CIRCULAR_GRATING}`),
      bracketProfile: named(params.bracketProfile, DEFAULT_BRACKET_PROFILE, `bracketProfile ${DEFAULT_BRACKET_PROFILE}`),
      ...(params.bracketSpacingMax === undefined ? {} : { bracketSpacingMax: params.bracketSpacingMax }),
      railing,
    };
    if (params.bracketSpacingMax === undefined)
      defaults.push('bracketSpacingMax: 8 deg steps (bars within 4 deg of perpendicular to the brackets)');
    const added = appendElements(
      building,
      [0],
      'assembly',
      (_, id, mark): AssemblyElement => ({
        id,
        category: 'assembly',
        mark,
        entityIds: [],
        levelId: vessel.levelId,
        kind: 'circular_platform',
        params: spec,
        partIds: [],
        hostId: vessel.id,
        generation: 0,
      }),
    );
    const assemblyId = added.ids[0] as string;
    const built = generate(doc, added.building, added.building.elements[assemblyId] as AssemblyElement, spec);
    if (!built.ok) return refusal(doc, 'add_circular_access_platform', built);
    return commitPlatform(doc, 'Added', assemblyId, built, defaults);
  },
});
