import { defineCommand, vec2, z } from '@core/commands/schema';
import type { CommandResult } from '@core/commands/types';
import { fromMm } from '@core/model/units';
import type { AssemblyElement } from '@aec/building/types';
import { appendElements, getBuilding, resolveLevel } from '../../../building/model';
import { levelIdParam } from '../../../building/levelParams';
import { refuse } from '../codes';
import { generate } from './platformRegenerate';
import { commitPlatform, refusal } from './platformCommit';
import { railingFieldParams, resolveRailingFields } from './platformRailing';
import type { PlatformSpec } from './platformSpec';

/** Default framing of a generated deck: section and largest beam spacing (named in data.defaults). */
export const DEFAULT_BEAM_PROFILE = 'IPE200';
export const DEFAULT_BEAM_SPACING_MM = 1000;

export const framingParam = z
  .union([
    z.literal('existing'),
    z.object({
      profile: z.string().optional().describe('Steel catalogue name of the secondary beams (list_steel_profiles). Default IPE200.'),
      maxSpacing: z
        .number()
        .positive()
        .optional()
        .describe('Largest distance between beams along the bars, DOCUMENT UNITS. Default 1000 mm.'),
    }),
  ])
  .describe(
    '{ profile?, maxSpacing? } generates the secondary beams (perpendicular to the bars, one at each end edge and equally spaced <= maxSpacing, top of steel at the grating underside); ' +
      '"existing" bears the panels on the horizontal beams already in the model (as add_grating does). Default: generated beams with the defaults.',
  );

export const deckRailingParam = z
  .object({
    edges: z
      .union([z.literal('all'), z.array(z.number().int().min(0)).min(1)])
      .optional()
      .describe(
        '"all" (default) or boundary edge indices: edge i runs from boundary point i to point i+1. Runs of consecutive edges are one railing.',
      ),
    ...railingFieldParams,
  })
  .describe(
    'Guard-rails along the deck edges (omit for none). Unset values follow the rulesets, as in add_railing, and are named in data.defaults.',
  );

/** The rectangle [[xmin, ymin], [xmax, ymax]] as a counter-clockwise ring. */
type Point = [number, number];

export const ringOfBounds = (bounds: readonly [Point, Point]): Point[] => {
  const [x0, x1] = [Math.min(bounds[0][0], bounds[1][0]), Math.max(bounds[0][0], bounds[1][0])];
  const [y0, y1] = [Math.min(bounds[0][1], bounds[1][1]), Math.max(bounds[0][1], bounds[1][1])];
  return [
    [x0, y0],
    [x1, y0],
    [x1, y1],
    [x0, y1],
  ];
};

/**
 * @affects creates 1 assembly element (mark AS<n>) plus its parts: secondary beams (role beam), grating panels (marks GR<n>) and guard-rails (RL<n>), all with assemblyId
 * @invariant beams at both end edges and <= maxSpacing apart with top of steel 0 mm under the grating underside; panels split at the beams like add_grating; the parts are read-only (derivation guard) and regenerated by update_access_platform
 * @failure unknown grating type -> STA_GRATING_TYPE_UNKNOWN; bad / non-convex region, zero direction, unknown profile, bad edges -> STA_INVALID_GEOMETRY; no beam at an end edge (framing existing) -> STA_NO_SUPPORT_FOUND; overlap at the same elevation -> STA_PLATFORM_OVERLAP
 */
export const addAccessPlatform = defineCommand({
  name: 'add_access_platform',
  description:
    'Generate a steel access platform (an assembly) over a convex plan region: secondary beams, open-bar grating panels and guard-rails in ONE step. ' +
    'It is not the civil earthworks add_platform. All lengths in DOCUMENT UNITS. Give the region as `boundary` (convex polygon, 3+ [x, y] points) or `bounds` ([[xmin, ymin], [xmax, ymax]]). ' +
    '`bearingBarDirection` [x, y] is the plan direction of the bearing bars; the beams run across it. `topOffset` = walking-surface height relative to the level elevation (default 0). ' +
    'The beams are generated (`framing` { profile, maxSpacing }) so that the panels bear on them, or `framing: "existing"` uses the beams already in the model. `railing` adds guard-rails on the boundary edges ' +
    '("all" or edge indices; unset values come from the rulesets: height 1100 mm, toe plate 100 mm, knee rails to keep the clear space, posts <= 1500 mm). ' +
    'The members, panels and railings are derived: they carry assemblyId and cannot be edited directly (CMD_DERIVED_GEOMETRY); change the platform with update_access_platform, delete it with delete_building_element on the assembly. ' +
    'Support columns are not generated: carry the beam ends on your own steel. Result data: assemblyId, partIds, memberIds, gratingIds, railingIds, quantities (area, kg, railing length, posts), defaults. check_access { ids: [assemblyId] } checks its gratings and railings.',
  params: z.object({
    gratingType: z.string().describe('Catalogue key from list_grating_types, e.g. "19-W-4 1-1/4x3/16".'),
    bearingBarDirection: vec2('Plan direction of the bearing bars [x, y] (any length, not zero); the beams run across it.'),
    boundary: z
      .array(vec2('Plan point [x, y], document units.'))
      .min(3)
      .optional()
      .describe('Convex region polygon. Give boundary or bounds, not both.'),
    bounds: z
      .tuple([vec2('Minimum corner [x, y].'), vec2('Maximum corner [x, y].')])
      .optional()
      .describe('Rectangular region [[xmin, ymin], [xmax, ymax]], document units. Give boundary or bounds, not both.'),
    topOffset: z.number().optional().describe('Walking-surface height relative to the level elevation, DOCUMENT UNITS. Default 0.'),
    framing: framingParam.optional(),
    railing: deckRailingParam.optional(),
    levelId: levelIdParam,
  }),
  run: (doc, params): CommandResult => {
    if ((params.boundary === undefined) === (params.bounds === undefined))
      return refuse(
        doc,
        'add_access_platform',
        'STA_INVALID_GEOMETRY',
        'give exactly one of boundary or bounds',
        [],
        ['boundary', 'bounds'],
      );
    const boundary: Point[] = params.boundary ?? (params.bounds === undefined ? [] : ringOfBounds(params.bounds));
    const defaults: string[] = [];
    if (params.topOffset === undefined) defaults.push('topOffset 0 (walking surface at the level elevation)');
    const framing: PlatformSpec['framing'] =
      params.framing === 'existing'
        ? { kind: 'existing' }
        : {
            kind: 'generated',
            profile: params.framing?.profile ?? DEFAULT_BEAM_PROFILE,
            maxSpacing: params.framing?.maxSpacing ?? fromMm(doc, DEFAULT_BEAM_SPACING_MM),
          };
    if (
      framing.kind === 'generated' &&
      (params.framing === undefined || params.framing === 'existing' || params.framing.profile === undefined)
    )
      defaults.push(`framing profile ${DEFAULT_BEAM_PROFILE}`);
    if (
      framing.kind === 'generated' &&
      (params.framing === undefined || params.framing === 'existing' || params.framing.maxSpacing === undefined)
    )
      defaults.push(`framing maxSpacing ${DEFAULT_BEAM_SPACING_MM} mm`);
    let railing: PlatformSpec['railing'] = null;
    if (params.railing !== undefined) {
      const { edges, ...input } = params.railing;
      const fields = resolveRailingFields(doc, input, defaults);
      if (typeof fields === 'string') return refuse(doc, 'add_access_platform', 'STA_INVALID_GEOMETRY', fields, [], ['railing']);
      railing = { edges: edges ?? 'all', ...fields };
    }
    const spec: PlatformSpec = {
      kind: 'platform',
      boundary,
      topOffset: params.topOffset ?? 0,
      gratingType: params.gratingType,
      bearingBarDirection: params.bearingBarDirection,
      framing,
      railing,
    };
    const building = getBuilding(doc);
    const resolution = resolveLevel(doc, building, params.levelId);
    if (!resolution.ok) return refuse(doc, 'add_access_platform', 'STA_INVALID_GEOMETRY', resolution.reason, [], ['levelId']);
    const added = appendElements(
      resolution.building,
      [0],
      'assembly',
      (_, id, mark): AssemblyElement => ({
        id,
        category: 'assembly',
        mark,
        entityIds: [],
        levelId: resolution.level.id,
        kind: 'platform',
        params: spec,
        partIds: [],
        generation: 0,
      }),
    );
    const assemblyId = added.ids[0] as string;
    const built = generate(doc, added.building, added.building.elements[assemblyId] as AssemblyElement, spec);
    if (!built.ok) return refusal(doc, 'add_access_platform', built);
    return commitPlatform(doc, 'Added', assemblyId, built, defaults);
  },
});
