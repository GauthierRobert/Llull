import { defineCommand, z } from '@core/commands/schema';
import type { CommandResult } from '@core/commands/types';
import type { AssemblyElement } from '@aec/building/types';
import { appendElements, getBuilding, resolveLevel } from '../../../building/model';
import { levelIdParam } from '../../../building/levelParams';
import { refuse } from '../codes';
import { generateRack } from './rackBuild';
import { rackFieldParams, resolveRack } from './rackParams';
import { commitRack, rackRefusal } from './rackCommit';
import { isRackProblem } from './rackLayout';

/**
 * @affects creates 1 assembly element (mark AS<n>) plus its steel members with assemblyId: columns (SC), rigid tier beams and pinned struts (SB), braces (BR)
 * @invariant bents = ceil(length / bentSpacing) + 1; columns = bents x column lines; tier beams = bents x tiers x bays across; struts = 2 x bays x tiers (two column lines); tier beams are rigid to the columns (moment frames for check_steel_members), struts pinned; the members are read-only (derivation guard) and regenerated by update_pipe_rack
 * @failure bentSpacing <= 0 / > length / too many bents -> STA_RACK_SPACING; tiers not ascending or too low -> STA_RACK_TIERS; bad bays, no profile or no struts for bracing -> STA_RACK_BRACING; unknown profile, zero direction -> STA_INVALID_GEOMETRY
 */
export const addPipeRack = defineCommand({
  name: 'add_pipe_rack',
  description:
    'Generate a steel pipe rack (an assembly) in ONE step: bents every bentSpacing along a direction, columns on the column lines up to the top tier, tier beams across each bent with RIGID joints to the columns (a transverse moment frame for check_steel_members), pinned longitudinal struts along the column lines and optional X-bracing in chosen bays. ' +
    'All lengths in DOCUMENT UNITS. Give the run as `length` + `bentSpacing` (n = ceil(length / bentSpacing) equal bays: 60 m at 6 m = 11 bents) or explicit `stations`, the width as `width` (two column lines) or `baysAcross`, and `tiers` as top-of-steel elevations above the level (a pipe resting on a tier beam has its underside there). ' +
    'The origin is the first bent on the first column line; the width extends to the left of `direction`. The members carry assemblyId and cannot be edited directly (CMD_DERIVED_GEOMETRY): change the rack with update_pipe_rack, remove it with delete_building_element on the assembly. ' +
    'No grid lines or foundations are created (bents and lines are named in the member notes with gridPrefix). Result data: assemblyId, partCount (the member ids are in affected and in the assembly partIds), bents, columns, tierBeams, struts, braces, lengths in metres (columnLengthM ...), steelMassKgExBracing (catalogue kg/m), defaults. ' +
    'Then run check_steel_members: pipes (add_pipe_run / route_pipe) resting on the tier beams load them with their steel + content weight, and data.racks reports the rack.',
  params: z.object({
    origin: rackFieldParams.origin,
    direction: rackFieldParams.direction,
    length: rackFieldParams.length.optional(),
    bentSpacing: rackFieldParams.bentSpacing.optional(),
    stations: rackFieldParams.stations.optional(),
    width: rackFieldParams.width.optional(),
    baysAcross: rackFieldParams.baysAcross.optional(),
    tiers: rackFieldParams.tiers,
    columnProfile: rackFieldParams.columnProfile,
    tierBeamProfile: rackFieldParams.tierBeamProfile,
    strutProfile: rackFieldParams.strutProfile.optional(),
    struts: rackFieldParams.struts.optional(),
    bracingBays: rackFieldParams.bracingBays.optional(),
    bracingProfile: rackFieldParams.bracingProfile.optional(),
    baseFixity: rackFieldParams.baseFixity.optional(),
    gridPrefix: rackFieldParams.gridPrefix.optional(),
    levelId: levelIdParam,
  }),
  run: (doc, params): CommandResult => {
    const { levelId, ...fields } = params;
    const defaults: string[] = [];
    const spec = resolveRack(fields, null, defaults);
    if (isRackProblem(spec)) return rackRefusal(doc, 'add_pipe_rack', spec);
    const resolution = resolveLevel(doc, getBuilding(doc), levelId);
    if (!resolution.ok) return refuse(doc, 'add_pipe_rack', 'STA_INVALID_GEOMETRY', resolution.reason, [], ['levelId']);
    const added = appendElements(
      resolution.building,
      [0],
      'assembly',
      (_, id, mark): AssemblyElement => ({
        id,
        category: 'assembly',
        mark,
        entityIds: [],
        levelId: resolution.level.id,
        kind: 'pipe_rack',
        params: spec,
        partIds: [],
        generation: 0,
      }),
    );
    const assemblyId = added.ids[0] as string;
    const built = generateRack(doc, added.building, added.building.elements[assemblyId] as AssemblyElement, spec);
    if (!built.ok) return rackRefusal(doc, 'add_pipe_rack', built);
    return commitRack(doc, 'Added', assemblyId, built, defaults);
  },
});
