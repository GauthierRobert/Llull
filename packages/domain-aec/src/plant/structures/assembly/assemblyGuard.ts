/** Derivation guard of the generated assemblies (06 STA M6 platforms, M7 pipe racks; architecture L8): generated members, gratings and railings are read-only. */

import type { DerivationGuard } from '@core/commands/derivation';
import type { AssemblyElement, AssemblyKind } from '@aec/building/types';
import { definitionOf } from './definition';

const UPDATE_COMMAND: Readonly<Record<AssemblyKind, string>> = {
  platform: 'update_access_platform',
  circular_platform: 'update_access_platform',
  pipe_rack: 'update_pipe_rack',
};

/**
 * A part of an assembly changes or disappears only through a regeneration of its assembly, which raises `generation`; deleting the assembly
 * takes its parts along. An edit of the assembly that does not regenerate it (a mark) is no escape, and a deleted assembly whose parts survive is refused.
 */
export const assemblyGuard: DerivationGuard = {
  domain: 'assembly',
  check(previous, next) {
    const before = previous.building;
    const after = next.building;
    if (before === undefined || after === undefined || before === after) return null;
    const edited: string[] = [];
    let owner: AssemblyElement | undefined;
    for (const element of Object.values(before.elements)) {
      if (element.category !== 'assembly') continue;
      const current = after.elements[element.id];
      const regenerated = current?.category === 'assembly' && (current as AssemblyElement).generation > element.generation;
      if (regenerated) continue;
      const deleted = current === undefined;
      for (const id of element.partIds) {
        const gone = after.elements[id] === undefined;
        if (deleted && gone) continue;
        if (definitionOf(after.elements[id], false) !== definitionOf(before.elements[id], false) || deleted) {
          edited.push(id);
          owner = element;
        }
      }
    }
    if (edited.length === 0 || owner === undefined) return null;
    const update = UPDATE_COMMAND[owner.kind];
    const parts = owner.kind === 'pipe_rack' ? 'members' : 'members, gratings and railings';
    return (
      `it would edit ${owner.kind === 'pipe_rack' ? 'pipe rack' : 'platform'} part(s) ${edited.slice(0, 5).join(', ')}${edited.length > 5 ? ' ...' : ''} generated by ${owner.id}. ` +
      `Edit the assembly instead: ${update} { assemblyId, ... } regenerates its ${parts}; delete_building_element on the assembly removes them all.`
    );
  },
};
