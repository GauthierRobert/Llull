import type { BuildingElement } from '@aec/building/types';
import { defineCommand, z } from '@core/commands/schema';
import type { CommandResult } from '@core/commands/types';
import { commitBuilding } from '../../../building/evaluate/evaluateElements';
import { getBuilding } from '../../../building/model';
import { refuse } from '../model';
import { followableRenames, followMarkInColourRules } from '../tagReferences';

/** Categories this command renames; equipment has rename_equipment_tag (references of pipes and lines follow), legacy pipes set_pipe_line_number. */
const RENAMEABLE_CATEGORIES = ['tray', 'pipeSupport', 'member'] as const;
type RenameableCategory = (typeof RENAMEABLE_CATEGORIES)[number];

export const isRenameable = (element: BuildingElement): element is Extract<BuildingElement, { category: RenameableCategory }> =>
  (RENAMEABLE_CATEGORIES as readonly string[]).includes(element.category);

/**
 * @affects changes the tag (mark) of cable trays, pipe supports and steel members, and the `mark` clauses (equals / in) of colour rules that named the old one
 * @invariant tags have no whitespace nor ':'; unique within the category after the whole batch (a swap is valid); geometry, ids and hosting (support -> pipe, plate -> member) are untouched; members of a generated assembly are read-only
 * @failure unknown element, other category, assembly part, bad or duplicate tag -> EQP_* refusal; an element classified by a plant object -> DAT_DIRECT_RENAME (plant-data guard); document unchanged
 */
export const renameElementTag = defineCommand({
  name: 'rename_element_tag',
  description:
    'Rename the tag (mark) of cable trays, pipe supports and steel members, so that assign_plant_object can classify them with a plant tag (plant data writes the tag back with this command). ' +
    'Equipment is renamed with rename_equipment_tag, legacy pipes (line number) with set_pipe_line_number. renames: [{ element (element id such as "tray-2", "support-3", "member-5", or its ' +
    'current tag when unambiguous), tag }]. The tag must not be empty nor contain whitespace or ":" and must be unique among the elements of the same category after the whole batch (a swap is valid). ' +
    'Members generated by a platform or pipe rack assembly are read-only (rename through the assembly). Display colour rules with a mark clause (equals / in) on the old tag follow the new one ' +
    '(data.colourRules). An element already classified with assign_plant_object is renamed through plant data, a direct rename is refused with DAT_DIRECT_RENAME (unassign_plant_object first). Returns data = { renamed [{ id, from, to }], colourRules }. Refusals: EQP_NOT_FOUND, EQP_PARAM_INVALID, EQP_TAG_DUPLICATE, EQP_ELEMENT_READONLY.',
  params: z.object({
    renames: z
      .array(
        z.object({
          element: z
            .string()
            .min(1)
            .describe(
              'Element id ("tray-2", "support-3", "member-5") or its current tag (mark) when that is unique among trays, supports and members.',
            ),
          tag: z.string().describe('New tag, e.g. "T-101": no whitespace, no ":".'),
        }),
      )
      .min(1)
      .max(10000)
      .describe('Elements and their new tags.'),
  }),
  run: (doc, params): CommandResult => {
    const building = getBuilding(doc);
    const targets = new Map<string, string>();
    for (const [index, entry] of params.renames.entries()) {
      const path = `renames[${index}]`;
      let element: BuildingElement | undefined = building.elements[entry.element];
      if (element === undefined) {
        const matches = building.elementOrder
          .map((id) => building.elements[id])
          .filter((other): other is BuildingElement => other !== undefined && isRenameable(other) && other.mark === entry.element);
        if (matches.length > 1)
          return refuse(
            doc,
            'rename_element_tag',
            'EQP_NOT_FOUND',
            `tag '${entry.element}' is ambiguous (${matches.map((match) => match.id).join(', ')}): pass the element id`,
            matches.map((match) => match.id),
            [`${path}.element`],
          );
        element = matches[0];
      }
      if (element === undefined || !isRenameable(element))
        return refuse(
          doc,
          'rename_element_tag',
          'EQP_NOT_FOUND',
          element === undefined
            ? `no tray, pipe support or steel member with id or tag '${entry.element}'`
            : `'${entry.element}' is a ${element.category}: only trays, pipe supports and steel members are renamed here (equipment: rename_equipment_tag, legacy pipes: set_pipe_line_number)`,
          element === undefined ? [] : [element.id],
          [`${path}.element`],
        );
      if (element.category === 'member' && element.assemblyId !== undefined)
        return refuse(
          doc,
          'rename_element_tag',
          'EQP_ELEMENT_READONLY',
          `member ${element.id} is generated by assembly ${element.assemblyId}`,
          [element.id],
          [`${path}.element`],
        );
      const tag = entry.tag.trim();
      if (tag === '' || /[:\s]/.test(tag))
        return refuse(
          doc,
          'rename_element_tag',
          'EQP_PARAM_INVALID',
          `tag "${entry.tag}" must not be empty nor contain whitespace or ':'`,
          [element.id],
          [`${path}.tag`],
        );
      targets.set(element.id, tag);
    }
    const finalMarks = new Map<string, string>();
    for (const id of building.elementOrder) {
      const element = building.elements[id];
      if (element === undefined || !isRenameable(element)) continue;
      const mark = targets.get(id) ?? element.mark;
      const key = `${element.category}:${mark}`;
      const twin = finalMarks.get(key);
      if (twin !== undefined)
        return refuse(
          doc,
          'rename_element_tag',
          'EQP_TAG_DUPLICATE',
          `tag '${mark}' would be used by ${twin} and ${id}`,
          [twin, id],
          ['renames'],
        );
      finalMarks.set(key, id);
    }
    const elements: Record<string, BuildingElement> = { ...building.elements };
    const renamed: Array<{ id: string; from: string; to: string }> = [];
    for (const [id, to] of targets) {
      const element = building.elements[id] as BuildingElement;
      if (element.mark === to) continue;
      renamed.push({ id, from: element.mark, to });
      elements[id] = { ...element, mark: to };
    }
    if (renamed.length === 0)
      return { document: doc, summary: 'rename_element_tag: every element already has these tags; nothing changed.', affected: [] };
    const ids = renamed.map((change) => change.id);
    const committed = commitBuilding(doc, { ...building, elements }, ids, '').document;
    const rules = followMarkInColourRules(
      committed,
      followableRenames(building.elements, new Set(ids), new Map(renamed.map((change) => [change.from, change.to]))),
    );
    const shown = renamed
      .slice(0, 4)
      .map((change) => `${change.id} ${change.from} -> ${change.to}`)
      .join(', ');
    return {
      document: rules.document,
      summary: `rename_element_tag: ${renamed.length} element(s) renamed (${shown}${renamed.length > 4 ? ', ...' : ''})${
        rules.followed.length === 0 ? '' : `; ${rules.followed.length} colour rule(s) followed (${rules.followed.join(', ')})`
      }.`,
      affected: ids,
      data: { renamed, colourRules: rules.followed, patternRules: rules.patterned },
    };
  },
});
