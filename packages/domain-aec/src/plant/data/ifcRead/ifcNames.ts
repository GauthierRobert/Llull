const PROPER = new Map<string, string>();
for (const name of [...Object.keys(IFC_SUPERTYPE), ...Object.values(IFC_SUPERTYPE), ...EXTRA_NAMES]) PROPER.set(name.toUpperCase(), name);

/** `IfcPipeSegment` for `IFCPIPESEGMENT`; a name this table does not know is returned as written. */
export const properName = (stepName: string): string => PROPER.get(stepName.toUpperCase()) ?? stepName;

/** Upper-case chain of `stepName` and its supertypes (`IFCPIPESEGMENT`, `IFCFLOWSEGMENT`, ...). */
export function typeChain(stepName: string): string[] {
  const chain: string[] = [];
  let current: string | undefined = properName(stepName);
  while (current !== undefined && chain.length < 12) {
    chain.push(current.toUpperCase());
    current = IFC_SUPERTYPE[current];
  }
  return chain;
}
