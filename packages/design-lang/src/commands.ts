/**
 * The design commands. A design is ONE feature step, `design_source { source, reads }`: its params are the `.lld` text, and every
 * regeneration (set_parameter, edit_step_params, undo, load) re-runs it. `apply_design` is the entry point; the others read the design.
 */

import { confirmExportControlled, defineCommand, z } from '@core/commands/schema';
import { execute } from '@core/commands/registry';
import { commandError, exportRefusal, noop, rejection, report } from '@core/commands/noop';
import type { CommandResult } from '@core/commands/types';
import { createEmptyDocument, type CadDocument, type FeatureStep } from '@core/model/types';
import { MM_PER_UNIT } from '@core/model/units';
import { attempt, DesignError, toCommandError } from './errors';
import { addedRecordKeys, withoutOwnRecords } from './regenerate';
import { parseDesign, type Statement } from './parse';
import { evaluateChecks, runDesign } from './run';
import { convertUnits } from './units';
import type { CheckResult } from './checks';

const DESIGN_STEP = 'design_source';

/** The document's design step (at most one), or undefined. */
function designStep(doc: CadDocument): FeatureStep | undefined {
  return doc.featureHistory.find((step) => step.name === DESIGN_STEP && !step.suppressed);
}

const sourceOf = (step: FeatureStep): string => String((step.params as { source?: unknown }).source ?? '');

const designRejection = (doc: CadDocument, command: string, error: DesignError): CommandResult =>
  rejection(doc, `${command}: ${error.code} — ${error.message}`, toCommandError(error));

function failedChecksText(checks: readonly CheckResult[]): string {
  const failed = checks.filter((c) => !c.pass);
  const more = failed.length > 10 ? `; … and ${failed.length - 10} more` : '';
  return (
    failed
      .slice(0, 10)
      .map(
        (c) =>
          `line ${c.line} ${c.metric}${c.of ? ` of ${c.of}` : ''}: expected ${c.op} ${JSON.stringify(c.expected)}, got ${JSON.stringify(c.actual)}`,
      )
      .join('; ') + more
  );
}

function checksSummary(checks: readonly CheckResult[]): string {
  if (checks.length === 0) return 'no checks';
  const failed = checks.filter((c) => !c.pass).length;
  return failed === 0
    ? `${checks.length}/${checks.length} checks pass`
    : `${checks.length - failed}/${checks.length} checks pass — FAILED ${failedChecksText(checks)}`;
}

/**
 * @affects runs the design: every entity its lines create (one feature step, ids `<prefix>-<step>.<k>`)
 * @invariant reads parameters, never writes them (apply_design sets the defaults); checks report, never fail the step
 * @failure any line fails -> input document, error DESIGN_* naming the line
 */
export const designSource = defineCommand({
  name: DESIGN_STEP,
  description:
    'The recorded design step: runs .lld design source (one feature step; regenerated by set_parameter / edit_step_params). Recorded by ' +
    'apply_design — call apply_design instead. data: { aliases, checks, commands }.',
  params: z.object({
    source: z.string().describe('.lld design source.'),
    reads: z
      .record(z.string(), z.union([z.number(), z.string()]))
      .describe('Parameter markers { name: "=name" } that make set_parameter regenerate this step (written by apply_design).'),
  }),
  annotations: { requiresKernel: true },
  run: (doc, { source }, ctx): CommandResult => {
    const run = attempt(() => {
      const statements = parseDesign(source);
      const stepKey = ctx?.stepKey;
      const regenerating = stepKey !== undefined && doc.featureHistory.some((step) => step.id === `step-${stepKey}`);
      const input = regenerating && ctx !== undefined ? withoutOwnRecords(doc, statements, ctx, stepKey) : doc;
      return { input, result: runDesign(input, statements, ctx) };
    });
    if (run instanceof DesignError) return designRejection(doc, DESIGN_STEP, run);
    const { input, result } = run;
    if (result.commands === 0)
      return designRejection(
        doc,
        DESIGN_STEP,
        new DesignError('DESIGN_SYNTAX', 0, 'the design runs no command', 'Add at least one command line.'),
      );
    return {
      document: result.document,
      summary: `design: ${result.commands} command(s), ${result.affected.length} entit${result.affected.length === 1 ? 'y' : 'ies'}; ${checksSummary(result.checks)}.`,
      affected: [...result.affected, ...addedRecordKeys(input, result.document)],
      data: { aliases: result.aliases, aliasGeometry: result.geometry, checks: result.checks, commands: result.commands },
    };
  },
});

/** Header `units=` (validated), or null. */
function headerUnits(statements: readonly Statement[]): CadDocument['units'] | null {
  const header = statements.find((s) => s.kind === 'header');
  if (header?.kind !== 'header') return null;
  let units: CadDocument['units'] | null = null;
  for (const pair of header.pairs) {
    const key = pair.key.join('.');
    const text = pair.value.kind === 'word' ? pair.value.text : '';
    if (key !== 'units') throw new DesignError('DESIGN_UNKNOWN_PARAM', header.line, `unknown design option "${key}"`, 'Options: units.');
    if (!(text in MM_PER_UNIT))
      throw new DesignError('DESIGN_BAD_ENUM', header.line, `"${text}" is not a unit`, `One of: ${Object.keys(MM_PER_UNIT).join(', ')}.`);
    units = text as CadDocument['units'];
  }
  return units;
}

/** Document units, then param defaults (an existing value wins, `set` overrides): every metaHistory / setter write, before the step. */
function prepareInputs(doc: CadDocument, statements: readonly Statement[], set: Readonly<Record<string, number>>): CadDocument {
  let current = doc;
  const units = headerUnits(statements);
  if (units !== null && units !== current.units) current = execute(current, 'set_units', { units }).document;
  const params = statements.filter((s): s is Extract<Statement, { kind: 'param' }> => s.kind === 'param');
  const unknown = Object.keys(set).filter((name) => !params.some((p) => p.name === name));
  if (unknown.length > 0)
    throw new DesignError(
      'DESIGN_UNKNOWN_PARAMETER',
      0,
      `set names undeclared param(s) ${unknown.join(', ')}`,
      'Declare them: param <name> = <default>.',
    );
  for (const param of params) {
    const value = set[param.name];
    if (value === undefined && current.parameters[param.name] !== undefined) continue;
    const expression = value === undefined ? convertUnits(param.expression, current, null, param.line) : String(value);
    const r = execute(current, 'set_parameter', { name: param.name, expression });
    const stored = r.document.parameters[param.name];
    if (stored === undefined || stored.error !== undefined)
      throw new DesignError(
        'DESIGN_BAD_VALUE',
        param.line,
        `param ${param.name} = ${param.expression}: ${stored?.error ?? r.summary}`,
        'Fix the expression (operators + - * / ( ), functions such as pow(a, b), sqrt, sin; other param names).',
      );
    current = r.document;
  }
  return current;
}

/** `{ name: "=name" }` for every document parameter the source mentions: set_parameter then regenerates the design step. */
function readsOf(doc: CadDocument, source: string): Record<string, string> {
  const words = new Set(source.match(/[A-Za-z_]\w*/g) ?? []);
  return Object.fromEntries(
    Object.keys(doc.parameters)
      .filter((name) => words.has(name))
      .map((name) => [name, `=${name}`]),
  );
}

/**
 * @affects sets document units / parameter defaults, then records (or replaces) the document's single design_source step
 * @invariant on any failure the input document is returned unchanged (units and parameters included)
 * @failure syntax / unknown command / failing line -> error DESIGN_* with its line; checks never fail it (see check_design)
 */
export const applyDesign = defineCommand({
  name: 'apply_design',
  description:
    'Build the model from a .lld design: one line per feature (`<command> <alias> key=value …`, any registered command), `param` ' +
    'defaults, anchors (face=base.top, on=base.top align=back), loops (for i in 0..n-1 { … }) and `check` lines. The design becomes the ' +
    "document's recipe: ONE feature step holding the source, re-run on every regeneration (set_parameter w=100 rebuilds it). A document " +
    'has one design; applying again replaces it. Fails with the line number on the first failing line (document unchanged). data: ' +
    '{ aliases, checks[] } — checks report, they never fail it (check_design gates). Language: describe_design_syntax.',
  params: z.object({
    source: z.string().describe('.lld design source (CLI: source=@text:part.lld).'),
    set: z
      .record(z.string(), z.number())
      .optional()
      .describe('Overrides for declared params, e.g. { "w": 100 } (otherwise an existing parameter value wins, then the param default).'),
  }),
  annotations: { metaHistory: true },
  run: (doc, { source, set }): CommandResult => {
    const prepared = attempt(() => prepareInputs(doc, parseDesign(source), set ?? {}));
    if (prepared instanceof DesignError) return designRejection(doc, 'apply_design', prepared);
    const params = { source, reads: readsOf(prepared, source) };
    const suppressed = prepared.featureHistory.find((step) => step.name === DESIGN_STEP && step.suppressed);
    if (suppressed !== undefined)
      return designRejection(
        doc,
        'apply_design',
        new DesignError(
          'DESIGN_BAD_VALUE',
          0,
          `the document's design (${suppressed.id}) is suppressed`,
          `Unsuppress it (set_step_suppressed stepId=${suppressed.id} suppressed=false) or delete it (delete_step) first.`,
        ),
      );
    const existing = designStep(prepared);
    const r =
      existing === undefined
        ? execute(prepared, DESIGN_STEP, params)
        : execute(prepared, 'edit_step_params', { stepId: existing.id, params });
    if (r.error !== undefined || r.rejected === true || r.document === prepared)
      return { ...noop(doc, `apply_design failed — ${r.summary}`), ...(r.error !== undefined ? { error: r.error } : {}) };
    const replaced = existing === undefined ? null : attempt(() => designChecks(r.document));
    const checks =
      replaced === null
        ? ((r.data as { checks?: CheckResult[] } | undefined)?.checks ?? [])
        : replaced instanceof DesignError
          ? []
          : replaced;
    const aliases = (r.data as { aliases?: Record<string, string[]> } | undefined)?.aliases;
    return {
      document: r.document,
      summary: `apply_design: ${existing === undefined ? 'recorded' : 'replaced'} the design (${r.affected.length} entities); ${checksSummary(checks)}.`,
      affected: r.affected,
      data: { checks, ...(aliases !== undefined ? { aliases } : {}) },
    };
  },
});

/**
 * The checks of `doc`'s design evaluated on `doc`: the design is re-run on an empty sandbox with the same step number (same ids) to
 * recover its aliases, then each check reads the real document.
 * @failure no design -> DESIGN_NO_DESIGN; the sandbox run fails -> its DesignError
 */
function designChecks(doc: CadDocument): CheckResult[] {
  const step = designStep(doc);
  if (step === undefined) throw new DesignError('DESIGN_NO_DESIGN', 0, 'the document has no design', 'Apply one with apply_design.');
  const stepNumber = Number(step.id.replace(/^step-/, ''));
  // A replay carries document-level inputs (layers, groups, …: core history/carry.ts), and a command such as import_dxf mints fewer ids
  // when its layer already exists. So the design re-runs on both starts — as replayed, then as first applied — and the run whose ids are
  // the document's names the aliases. Its materials are its own; only a design using outside materials needs the document's.
  const replayed: Partial<CadDocument> = {
    camera: doc.camera,
    displayPrecision: doc.displayPrecision,
    animations: doc.animations,
    groups: doc.groups,
    layers: doc.layers,
    layerOrder: doc.layerOrder,
    configurations: doc.configurations,
    recipes: doc.recipes,
  };
  const sandbox = (carried: Partial<CadDocument>, materials: CadDocument['materials']): CadDocument => ({
    ...createEmptyDocument(),
    ...carried,
    units: doc.units,
    parameters: doc.parameters,
    materials,
    nextStepNumber: stepNumber,
  });
  type AliasData = { aliases?: Record<string, string[]>; aliasGeometry?: Record<string, string[]> } | undefined;
  const checksWith = (data: AliasData): CheckResult[] =>
    evaluateChecks(doc, parseDesign(sourceOf(step)), data?.aliases ?? {}, data?.aliasGeometry ?? {});
  let fallback: CommandResult | null = null;
  // Outside materials are tried only when the design fails without them.
  for (const materials of [{}, doc.materials]) {
    const runs = [sandbox(replayed, materials), sandbox({}, materials)].map((start) => execute(start, DESIGN_STEP, step.params));
    const ok = runs.filter((r) => r.error === undefined);
    fallback ??= runs[0] ?? null;
    const matching = ok.find((r) =>
      Object.values((r.data as AliasData)?.aliasGeometry ?? {})
        .flat()
        .every((id) => r.document.entities[id] === undefined || doc.entities[id] !== undefined),
    );
    const chosen = matching ?? ok[0];
    if (chosen !== undefined) return checksWith(chosen.data as AliasData);
  }
  throw new DesignError(
    'DESIGN_STEP_FAILED',
    0,
    `the design does not re-run on its own: ${fallback?.summary ?? ''}`,
    fallback?.error?.remediation ?? '',
  );
}

/**
 * @affects nothing — read-only
 * @failure no design -> DESIGN_NO_DESIGN; a failing check -> error DESIGN_CHECK_FAILED (CLI exit 1), data still lists every check
 */
export const checkDesign = defineCommand({
  name: 'check_design',
  description:
    "Evaluate the `check` lines of the document's design against the current document (after any later edits). Fails with " +
    'DESIGN_CHECK_FAILED when a check fails (CLI exit 1: use it as a gate). data: { checks[]: { line, metric, of, op, expected, actual, ' +
    'tolerance, pass }, passed, failed }.',
  params: z.object({}),
  annotations: { readOnly: true },
  run: (doc): CommandResult => {
    const checks = attempt(() => designChecks(doc));
    if (checks instanceof DesignError) return designRejection(doc, 'check_design', checks);
    const failed = checks.filter((c) => !c.pass).length;
    const data = { checks, passed: checks.length - failed, failed };
    if (failed === 0) return report(doc, `check_design: ${checksSummary(checks)}.`, data);
    return {
      ...report(doc, `check_design: ${checksSummary(checks)}.`, data),
      error: commandError(
        'DESIGN_CHECK_FAILED',
        'Fix the design (or the expectation) at the failing line(s).',
        [],
        checks.filter((c) => !c.pass).map((c) => `line ${c.line}`),
      ),
    };
  },
});

/** @affects nothing — read-only; @failure no design -> DESIGN_NO_DESIGN */
export const exportDesign = defineCommand({
  name: 'export_design',
  description:
    "Return the document's design source (.lld) verbatim: data { text, fileName } (CLI: --save part.lld). Behind the export gate like " +
    'every export (an export-controlled document needs a human confirmation).',
  params: z.object({ confirmExportControlled }),
  annotations: { readOnly: true },
  run: (doc, { confirmExportControlled: confirmation }, ctx): CommandResult => {
    const refused = exportRefusal(doc, 'export_design', 'code', confirmation, ctx);
    if (refused !== null) return refused;
    const step = designStep(doc);
    if (step === undefined)
      return designRejection(
        doc,
        'export_design',
        new DesignError('DESIGN_NO_DESIGN', 0, 'the document has no design', 'Apply one with apply_design.'),
      );
    const source = sourceOf(step);
    const name = /^\s*design\s+([A-Za-z_]\w*)/m.exec(source)?.[1] ?? 'design';
    return report(doc, `export_design: ${source.split('\n').length} line(s).`, { text: source, fileName: `${name}.lld` });
  },
});
