/**
 * Plugin contract: a domain (building, industrial, …) extends the CAD core by contributing commands, a toolset, derivation guards and
 * a deriver — without the core importing it.
 * @invariant core/** never imports a plugin; the app composition root installs plugins
 */

import type { CadDocument } from '../model/types';
import type { DrawingSheet } from '../model/sheet';
import type { FastenerRef } from '../model/features';
import type { CommandDefinition, RetiredCommandRewrite } from '../commands/types';
import type { DerivationGuard } from '../commands/derivation';
import type { EntityPropertyProvider } from '../model/entityProperties';

/** Clearance-hole size resolved from a standard-part reference (see `DocumentProjections.fastenerHole`). */
export interface FastenerHoleSize {
  /** Document length units. */
  readonly diameter: number;
  readonly source: string;
}

/**
 * Read-only views of a plugin's slice that core renderers and checks consume without knowing the slice (architecture L10). Each member is
 * offered by at most one plugin; core uses the first installed extension that defines it.
 * @invariant pure queries: never modify the document
 */
export interface DocumentProjections {
  /** The sheet as printed (title block follows the managed item) and the export-control notice for the frame. */
  printedSheet?(doc: CadDocument, sheet: DrawingSheet): { readonly sheet: DrawingSheet; readonly notice: string | undefined };
  /** Active inspection-characteristic number of PMI item `pmiId`, or undefined (drawn as a balloon). */
  characteristicNumber?(doc: CadDocument, pmiId: string): number | undefined;
  /** Clearance-hole diameter of a catalogued fastener, or the reason it cannot be resolved. */
  fastenerHole?(doc: CadDocument, ref: FastenerRef): FastenerHoleSize | string;
  /** Number of placed fastener stacks, or undefined when the document has none. */
  fastenerStackCount?(doc: CadDocument): number | undefined;
}

/** A plugin's slice of the document: validation of its data and re-derivation of its geometry. */
export interface DocumentExtension {
  /** Value errors in the plugin's raw document data (persistence rejects the file when non-empty). */
  validate(raw: Record<string, unknown>): string[];
  /** Entity ids this domain regenerates from the definition. */
  derivedEntityIds(doc: CadDocument): ReadonlySet<string>;
  /**
   * Restore omitted geometry on a migrated, not-yet-validated raw document.
   * @invariant returns `raw` unchanged when the domain data is absent or invalid
   */
  restore(raw: Record<string, unknown>): Record<string, unknown>;
  /**
   * Slices `replayHistory` must neither lose nor regenerate (document input state the plugin's metaHistory commands own): called AFTER the
   * steps with the pre-replay document and the replayed document, returns the replayed document plus those slices (so a plugin guard never sees the
   * regenerated steps as edits of its slice).
   * @invariant pure; returns `next` unchanged when the plugin has no data in `prev`
   */
  carry?(prev: CadDocument, next: CadDocument): CadDocument;
  /**
   * Warnings about a loaded, validated document (e.g. a PLM integrity mismatch); `load_document` appends each to its summary.
   * @invariant a pure query: cannot modify the document
   */
  afterLoad?(doc: CadDocument): readonly string[];
  /**
   * Slices a replay seeds from the pre-replay document: identity that must survive while the slice's content is regenerated by the steps
   * (e.g. the building's IFC GlobalId salt).
   * @invariant pure; returns {} when the plugin has no such state in `base`
   */
  replaySeed?(base: CadDocument): Partial<CadDocument>;
  /**
   * A globally unique id the plugin's commands may mint into the document (e.g. `uniqueId`); a replay step that mints one is never memoized.
   * @invariant pure; undefined when the document holds none
   */
  mintedIdentity?(doc: CadDocument): string | undefined;
  /** Top-level document keys that are not part of the release-scope content hash (e.g. the PLM record itself). */
  readonly outsideReleaseScope?: readonly string[];
  readonly projections?: DocumentProjections;
}

export interface CadPlugin {
  /** Unique plugin id, e.g. `building`. */
  readonly name: string;
  /** Toolset its commands belong to in CLI listings and the UI palette (see @protocol/toolsets). */
  readonly toolset: string;
  readonly commands: ReadonlyArray<CommandDefinition<unknown>>;
  readonly guards?: ReadonlyArray<DerivationGuard>;
  readonly document?: DocumentExtension;
  /** Domain properties of an entity for colour rules and reports (`ExecutionContext.properties`); pure, {} for entities it does not own. */
  readonly entityProperties?: EntityPropertyProvider;
  /** Retired command name -> rewrite onto its replacement (saved steps are migrated on load). */
  readonly retiredCommands?: Readonly<Record<string, RetiredCommandRewrite>>;
}
