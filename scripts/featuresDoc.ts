/**
 * docs/FEATURES.md generator (SC-Q5): every registered command (`listCommands()`, default plugins installed) grouped by toolset, one
 * line each. Deterministic (no dates). Written by `npm run features`; tests/unit/contract/featuresDoc.test.ts fails when it is stale.
 */

import { listCommands } from '@core/commands/registry';
import type { CommandDefinition } from '@core/commands/types';
import { TOOLSET_NAMES, toolsetOf, type ToolsetName } from '@protocol/toolsets';

const MAX_DESCRIPTION_CHARS = 160;

/** First sentence of a description, one line, table-safe. */
function oneLine(description: string): string {
  const flat = description.replace(/\s+/g, ' ').trim();
  const sentence = /^(.+?[.!?])(\s|$)/.exec(flat)?.[1] ?? flat;
  const capped = sentence.length <= MAX_DESCRIPTION_CHARS ? sentence : `${sentence.slice(0, MAX_DESCRIPTION_CHARS - 1)}…`;
  return capped.replace(/\|/g, '\\|');
}

function flags(def: CommandDefinition<unknown>): string {
  const annotations = def.annotations ?? {};
  return [annotations.readOnly === true ? 'read-only' : '', annotations.requiresKernel === true ? 'kernel' : ''].filter(Boolean).join(', ');
}

export function featuresMarkdown(): string {
  const commands = listCommands();
  const groups = new Map<ToolsetName, CommandDefinition<unknown>[]>();
  for (const def of commands) {
    const toolset = toolsetOf(def.name) ?? 'core';
    groups.set(toolset, [...(groups.get(toolset) ?? []), def]);
  }
  const lines = [
    '# llull features',
    '',
    '<!-- Generated by `npm run features` from the command registry (listCommands, default plugins). Do not edit by hand:',
    '     npm run check fails when this file is stale. -->',
    '',
    `${commands.length} commands in ${groups.size} toolsets. Every command is one UI action and one \`llull\` CLI tool ` +
      '(`llull describe <name>` prints its parameters). Flags: **read-only** never changes the document; **kernel** needs the geometry ' +
      'kernel (exact B-rep with the native OCCT kernel). Host exchange tools (STEP/DWG/code import-export, FE solve) are listed by `llull list exchange`.',
    '',
    '| Toolset | Commands |',
    '| ------- | -------- |',
    ...TOOLSET_NAMES.filter((name) => groups.has(name)).map((name) => `| [${name}](#${name}) | ${groups.get(name)?.length ?? 0} |`),
  ];
  for (const name of TOOLSET_NAMES) {
    const defs = [...(groups.get(name) ?? [])].sort((a, b) => a.name.localeCompare(b.name));
    if (defs.length === 0) continue;
    lines.push('', `## ${name}`, '', '| Command | Description | Flags |', '| ------- | ----------- | ----- |');
    for (const def of defs) lines.push(`| \`${def.name}\` | ${oneLine(def.description)} | ${flags(def)} |`);
  }
  return `${lines.join('\n')}\n`;
}
