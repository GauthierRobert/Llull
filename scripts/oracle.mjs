// npm run oracle: runs the oracle suite (tests/oracle on the Manifold mesh kernel, server/tests/oracle.test.ts on the native OCCT kernel
// when the binary is built) and writes docs/ORACLE.md from the per-case results.
import { spawnSync } from 'node:child_process';
import { existsSync, mkdtempSync, readFileSync, readdirSync, rmSync, writeFileSync } from 'node:fs';
import { tmpdir } from 'node:os';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const resultsDir = mkdtempSync(path.join(tmpdir(), 'llull-oracle-'));
const env = { ...process.env, ORACLE_RESULTS_DIR: resultsDir };

function vitest(cwd, args) {
  const bin = path.join(cwd, 'node_modules', 'vitest', 'vitest.mjs');
  if (!existsSync(bin)) return null;
  return spawnSync(process.execPath, [bin, 'run', ...args], { cwd, env, stdio: 'inherit' }).status;
}

const statuses = [vitest(root, ['tests/oracle', '--project', 'node']), vitest(path.join(root, 'server'), ['tests/oracle.test.ts'])];

const load = (kernel) => {
  const file = path.join(resultsDir, `${kernel}.json`);
  return existsSync(file) ? JSON.parse(readFileSync(file, 'utf8')) : null;
};
const results = { manifold: load('manifold'), occt: load('occt') };
const expectedById = new Map(
  readdirSync(path.join(root, 'tests', 'oracle'), { withFileTypes: true })
    .filter((entry) => entry.isDirectory() && /^\d\d-/.test(entry.name))
    .map((entry) => [entry.name, JSON.parse(readFileSync(path.join(root, 'tests', 'oracle', entry.name, 'expected.json'), 'utf8'))]),
);
const rowOf = (kernel, id) => results[kernel]?.rows.find((row) => row.id === id);
const num = (x) => (x === null || x === undefined ? '-' : Number(x.toPrecision(7)).toString());
const err = (x) => (x === null || x === undefined ? '-' : x.toExponential(1));
const cell = (row) =>
  row === undefined
    ? ['not run', '-', '-']
    : row.status === 'skipped'
      ? ['n/a', '-', 'skipped']
      : [num(row.volumeMeasured), err(row.volumeRelError), row.status];

const count = (kernel, status) => results[kernel]?.rows.filter((row) => row.status === status).length ?? 0;
const lines = [
  '# Oracle reference parts (SC-Q1)',
  '',
  'Generated by `npm run oracle` (`scripts/oracle.mjs`). Each case is a `build_project` plan (`tests/oracle/<nn-name>/plan.json`) measured with',
  '`mass_properties` / `measure_bounding_box` and compared with `expected.json`: volume and area (relative 1e-3), centre of mass and bbox',
  '(1e-3 of the part size). Every expectation is `source: analytic` (closed form, `tools/oracle-analytic/`); FreeCAD-derived values',
  '(`tools/freecad-oracle/`) are not available here and none are claimed. A mesh kernel gets the per-case `meshTolerance` recorded in',
  '`expected.json` (tessellated curved surfaces, reason stored with it); the native OCCT run uses the tight tolerances and adds a STEP round trip.',
  '',
  '## Summary',
  '',
  '| kernel | cases run | pass | known failure | fail | skipped |',
  '| --- | --- | --- | --- | --- | --- |',
];
for (const [kernel, label] of [
  ['manifold', 'Manifold 3D (in-process mesh kernel, `tests/oracle`)'],
  ['occt', 'native OCCT (`llull-kernel`, `server/tests/oracle.test.ts`)'],
]) {
  const data = results[kernel];
  if (data === null) lines.push(`| ${label} | not run (binary not built on the machine that generated this file) | - | - | - | - |`);
  else {
    const skipped = count(kernel, 'skipped');
    lines.push(
      `| ${label} | ${data.rows.length - skipped} | ${count(kernel, 'pass')} | ${count(kernel, 'known-failure')} | ${count(kernel, 'fail')} | ${skipped} |`,
    );
  }
}
const families = new Map();
for (const e of expectedById.values()) families.set(e.family, (families.get(e.family) ?? 0) + 1);
lines.push('', `Cases: ${expectedById.size} (${[...families].map(([family, n]) => `${family} ${n}`).join(', ')}).`, '');

const known = [...expectedById.values()].filter((e) => e.knownFailure !== undefined);
if (known.length > 0) {
  lines.push('## Known failures (real findings, not loosened)', '');
  for (const e of known)
    lines.push(
      `- \`${e.id}\` (${e.knownFailure.fields.join(', ')}${e.knownFailure.kernels ? `; ${e.knownFailure.kernels.join(', ')} only` : ''}): ${e.knownFailure.diagnosis}`,
    );
  lines.push('');
}
lines.push(
  '## Cases',
  '',
  'V = volume. Relative errors are |measured - expected| / expected. `STEP` is the export_step_exact / import_step_exact round trip (OCCT only).',
  '',
  '| id | source | V expected | Manifold V | rel err | Manifold | OCCT V | rel err | OCCT | STEP |',
  '| --- | --- | --- | --- | --- | --- | --- | --- | --- | --- |',
);
for (const [id, e] of expectedById) {
  const m = cell(rowOf('manifold', id));
  const o = cell(rowOf('occt', id));
  lines.push(
    `| ${id} | ${e.source} | ${num(e.volume)} | ${m.join(' | ')} | ${o.join(' | ')} | ${rowOf('occt', id)?.stepRoundTrip ?? '-'} |`,
  );
}
lines.push('');
writeFileSync(path.join(root, 'docs', 'ORACLE.md'), `${lines.join('\n')}`, 'utf8');
rmSync(resultsDir, { recursive: true, force: true });
process.stdout.write(`wrote docs/ORACLE.md (${expectedById.size} cases)\n`);
process.exit(statuses.some((status) => status !== null && status !== 0) ? 1 : 0);
