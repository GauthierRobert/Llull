// Variable chamfer (BLD M5, docs/design/06-variable-blends/TECHNICAL_SPEC.md §5.7 and §13.14): OCCT's MakeChamfer takes constant distances, so a
// chamfer whose distance runs linearly from `first` at the start of a straight edge to `last` at its end is the boolean of the source with a
// ruled loft of the two corner triangles (corner, point at the distance on face 1, point at the distance on face 2). The lateral face of the
// loft is the bilinear patch whose cross-section at every station is the straight chamfer section of that station's distance, so the removed
// volume of a right-angle edge is exactly 1/2 integral d(s)^2 ds. CUT for a convex edge, FUSE for a concave one (blend_tool.hxx `apply_tools`).
// Scope: symmetric legs, straight edges between planar faces, flat square ends, no two chosen edges sharing a vertex.
