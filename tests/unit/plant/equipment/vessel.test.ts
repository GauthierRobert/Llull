import { describe, expect, it } from 'vitest';
import { execute } from '@core/commands/registry';
import { closedFormVolume } from '@core/geometry/closedFormVolume';
import { chainIssue } from '@core/geometry/curveSegments';
import type { RevolutionEntity } from '@core/model/types';
import type { EquipmentElement } from '@aec/building/types';
import { apply, data, expectRefusal, ok } from '../../../helpers/commandAssertions';
import { drumParams, mmDocument, separatorDocument, separatorParams } from './equipmentFixtures';
import { headMetalVolume } from '@aec/plant/equipment/geometry/headOffset';
import { resolveHead } from '@aec/plant/equipment/geometry/heads';

const rel = (actual: number, expected: number): number => Math.abs(actual / expected - 1);
const equipmentOf = (doc: ReturnType<typeof mmDocument>, index = 0): EquipmentElement =>
  Object.values(doc.building?.elements ?? {}).filter((element): element is EquipmentElement => element.category === 'equipment')[
    index
  ] as EquipmentElement;

describe('add_vessel: vertical separator (SC-EQP-01)', () => {
  const result = ok(mmDocument(), 'add_vessel', separatorParams);
  const element = equipmentOf(result.document);

  it('creates one tagged equipment element and its derived solids', () => {
    expect(element.mark).toBe('V-101');
    expect(element.name).toBe('HP separator');
    expect(element.location).toEqual([5000, 5000]);
    expect(result.affected[0]).toBe(element.id);
    expect(element.entityIds).toEqual([`${element.id}:body`, `${element.id}:skirt`]);
    for (const id of element.entityIds) {
      expect(result.document.entities[id]?.tags).toContain(`element:${element.id}`);
      expect(result.document.order).toContain(id);
    }
    expect(data<{ bottomTangentLine: number; topTangentLine: number }>(mmDocument(), 'add_vessel', separatorParams)).toMatchObject({
      bottomTangentLine: 2000,
      topTangentLine: 6000,
      elementId: element.id,
      tag: 'V-101',
      angleConvention: 'north_cw',
    });
  });

  it('re-derives the legacy fields: vertical_vessel, bounding box of body + skirt, operating weight', () => {
    expect(element.shape).toBe('vertical_vessel');
    expect(element.size).toEqual([1540, 1540, 6385]);
    // VC-EQP-09: shell + 2 exact offset heads + skirt (ID = shell OD) + 850 kg/m3 x 3.0925 m3
    expect(rel(element.weight, 5262.099607204157)).toBeLessThan(1e-9);
  });

  it('draws the body as ONE exact revolution whose Pappus volume matches the shell + head metal volumes', () => {
    const body = result.document.entities[`${element.id}:body`] as RevolutionEntity;
    expect(body.kind).toBe('revolution');
    expect(body.axis).toEqual([0, 0, 1]);
    expect(body.segments).toBeGreaterThanOrEqual(64);
    expect(body.position).toEqual([5000, 5000, 0]);
    expect(chainIssue(body.curves ?? [], true)).toBeNull();
    const head = resolveHead({ type: 'ellipsoidal', ratio: 2 }, 750, 'h');
    if ('error' in head) throw new Error(head.error);
    const metal = Math.PI * (760 ** 2 - 750 ** 2) * 4000 + 2 * headMetalVolume(head.shape, 750, 10);
    // Bézier chain through exact offset points + 16-step tessellation of each Bézier: within 1e-4
    expect(rel(closedFormVolume(body)?.volume ?? 0, metal)).toBeLessThan(1e-4);
  });

  it('is pure and re-derivable: the input document is untouched and entities are read-only under the building guard', () => {
    const before = mmDocument();
    const snapshot = JSON.stringify(before);
    execute(before, 'add_vessel', separatorParams);
    expect(JSON.stringify(before)).toBe(snapshot);
    const moved = execute(result.document, 'move_entities', { ids: [`${element.id}:body`], delta: [10, 0, 0] });
    expect(moved.summary).toMatch(/rejected: it would edit geometry generated by building element/);
  });

  it('defaults are named, never silent', () => {
    const bare = { ...separatorParams, headThickness: undefined, corrosionAllowance: undefined, support: { type: 'skirt', height: 2000 } };
    const defaulted = data<{ defaulted: string[] }>(mmDocument(), 'add_vessel', bare).defaulted;
    expect(defaulted).toEqual(
      expect.arrayContaining(['headThickness', 'corrosionAllowance', 'support.thickness', 'support.baseRingWidth']),
    );
  });

  it('reads planRotationDeg with the angle convention', () => {
    const north = equipmentOf(apply(mmDocument(), 'add_vessel', { ...separatorParams, planRotationDeg: 90 }));
    const east = equipmentOf(apply(mmDocument(), 'add_vessel', { ...separatorParams, planRotationDeg: 90, angleConvention: 'east_ccw' }));
    expect(north.angle).toBeCloseTo(-Math.PI / 2, 12);
    expect(east.angle).toBeCloseTo(Math.PI / 2, 12);
  });
});

describe('add_vessel: horizontal drum on saddles (SC-EQP-02)', () => {
  const doc = apply(mmDocument(), 'add_vessel', drumParams);
  const element = equipmentOf(doc);

  it('places the axis 1500 above the level, two saddle blocks, derived box legacy fields', () => {
    expect(element.entityIds).toEqual([`${element.id}:body`, `${element.id}:saddle-1`, `${element.id}:saddle-2`]);
    const body = doc.entities[`${element.id}:body`] as RevolutionEntity;
    expect(body.axis).toEqual([1, 0, 0]);
    expect(body.position).toEqual([0, 0, 1500]);
    expect(element.shape).toBeUndefined();
    expect(element.size).toEqual([7032, 2036, 2518]);
    // VC-EQP-09 SC-EQP-02 body.emptyKg (saddle plates are not part of the weight)
    expect(rel(element.weight, 6485.731147911467)).toBeLessThan(1e-9);
    expect(doc.entities[`${element.id}:saddle-1`]?.position).toEqual([-1800, 0, 241]);
  });

  it('sits on the floor as a horizontal_vessel when there is no raised support', () => {
    const floor = equipmentOf(apply(mmDocument(), 'add_vessel', { ...drumParams, support: { type: 'none' } }));
    expect(floor.shape).toBe('horizontal_vessel');
    expect(floor.size).toEqual([7032, 2036, 2036]);
  });
});

describe('add_vessel: refusals leave the document unchanged with a stable code and path', () => {
  const base = mmDocument();
  it.each([
    [
      'duplicate tag',
      () => ({ doc: separatorDocument(false), params: { ...separatorParams, location: [0, 0] }, code: 'EQP_TAG_DUPLICATE', path: 'tag' }),
    ],
    [
      'thickness not above the allowance',
      () => ({ doc: base, params: { ...separatorParams, shellThickness: 3 }, code: 'EQP_PARAM_INVALID', path: 'shellThickness' }),
    ],
    [
      'head thickness not above the allowance',
      () => ({ doc: base, params: { ...separatorParams, headThickness: 2 }, code: 'EQP_PARAM_INVALID', path: 'headThickness' }),
    ],
    [
      'missing top head',
      () => ({
        doc: base,
        params: { ...separatorParams, heads: { bottom: { type: 'flat' } } },
        code: 'EQP_PARAM_INVALID',
        path: 'heads.top',
      }),
    ],
    [
      'head of the other orientation',
      () => ({
        doc: base,
        params: { ...separatorParams, heads: { ...separatorParams.heads, left: { type: 'flat' } } },
        code: 'EQP_PARAM_INVALID',
        path: 'heads.left',
      }),
    ],
    [
      'torispherical head without standard or radii',
      () => ({
        doc: base,
        params: { ...separatorParams, heads: { top: { type: 'torispherical' }, bottom: { type: 'flat' } } },
        code: 'EQP_HEAD_INVALID',
        path: 'heads.top.standard',
      }),
    ],
    [
      'saddles on a vertical vessel',
      () => ({
        doc: base,
        params: { ...separatorParams, support: { type: 'saddles', stations: [1000], width: 200, axisElevation: 2000 } },
        code: 'EQP_SUPPORT_INVALID',
        path: 'support.type',
      }),
    ],
    [
      'skirt on a horizontal vessel',
      () => ({
        doc: base,
        params: { ...drumParams, support: { type: 'skirt', height: 1000 } },
        code: 'EQP_SUPPORT_INVALID',
        path: 'support.type',
      }),
    ],
    [
      'skirt without height',
      () => ({
        doc: base,
        params: { ...separatorParams, support: { type: 'skirt' } },
        code: 'EQP_SUPPORT_INVALID',
        path: 'support.height',
      }),
    ],
    [
      'two legs',
      () => ({
        doc: base,
        params: { ...separatorParams, support: { type: 'legs', count: 2, height: 1500 } },
        code: 'EQP_SUPPORT_INVALID',
        path: 'support.count',
      }),
    ],
    [
      'saddle station outside the tangent length',
      () => ({
        doc: base,
        params: { ...drumParams, support: { type: 'saddles', stations: [1200, 7000], width: 250, axisElevation: 1500 } },
        code: 'EQP_SUPPORT_INVALID',
        path: 'support.stations.1',
      }),
    ],
    [
      'axis below the shell outside radius',
      () => ({
        doc: base,
        params: { ...drumParams, support: { type: 'saddles', stations: [1200], width: 250, axisElevation: 900 } },
        code: 'EQP_SUPPORT_INVALID',
        path: 'support.axisElevation',
      }),
    ],
    [
      'unknown level',
      () => ({ doc: base, params: { ...separatorParams, levelId: 'level-99' }, code: 'EQP_PARAM_INVALID', path: 'levelId' }),
    ],
    ['blank tag', () => ({ doc: base, params: { ...separatorParams, tag: '  ' }, code: 'EQP_PARAM_INVALID', path: 'tag' })],
  ])('%s', (_name, build) => {
    const { doc, params, code, path } = build();
    expectRefusal(doc, 'add_vessel', params, code, path);
  });

  it('a vertical vessel with legs derives their footprint and weight', () => {
    const legs = equipmentOf(apply(mmDocument(), 'add_vessel', { ...separatorParams, support: { type: 'legs', count: 4, height: 1500 } }));
    expect(legs.shape).toBe('vertical_vessel');
    expect(legs.size[2]).toBeCloseTo(1500 + 4000 + 375 + 10, 9);
    expect(legs.entityIds.filter((id) => id.includes(':leg-'))).toHaveLength(4);
  });
});
