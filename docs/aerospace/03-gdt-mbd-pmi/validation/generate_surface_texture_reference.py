#!/usr/bin/env python3
"""Analytic surface-texture parameter values for ideal periodic profiles (gap GDT, VC-GDT-40).

Purpose: give a future `evaluate_surface_texture` query (llull, optional V2) closed-form expected values
for the amplitude parameters of an already-filtered roughness profile z(x) with mean line z = 0, over
an integer number of periods. The definitions used are the textbook integral definitions of the
arithmetic mean deviation (Ra), root-mean-square deviation (Rq), skewness (Rsk), kurtosis (Rku) and
maximum height within one sampling length (Rz = Rp + Rv). Filtering (cut-offs), evaluation lengths and
the ISO 21920-2 / ASME B46.1 parameter rules are NOT reproduced here (paywalled; see sources.md).

Closed forms (amplitude A, period p, any integer number of periods):
  sine      z = A sin(2 pi x / p): Ra = 2A/pi, Rq = A/sqrt(2), Rsk = 0, Rku = 3/2, Rz = 2A
  triangle  symmetric, peak +-A:   Ra = A/2,   Rq = A/sqrt(3), Rsk = 0, Rku = 9/5, Rz = 2A
  square    +-A, 50 % duty:        Ra = A,     Rq = A,         Rsk = 0, Rku = 1,   Rz = 2A
Each closed form is cross-checked by midpoint-rule integration (100 000 samples per period).

Usage: python3 -I generate_surface_texture_reference.py   (rewrites surface_texture_reference.json)
"""

from __future__ import annotations

import json
import math
import os

HERE = os.path.dirname(os.path.abspath(__file__))
SAMPLES = 100_000


def profiles(a: float):
    return {
        'sine': (lambda u: a * math.sin(2 * math.pi * u), {'Ra': 2 * a / math.pi, 'Rq': a / math.sqrt(2), 'Rsk': 0.0, 'Rku': 1.5, 'Rz': 2 * a}),
        'triangle': (
            lambda u: a * (4 * u - 1 if u < 0.5 else 3 - 4 * u),
            {'Ra': a / 2, 'Rq': a / math.sqrt(3), 'Rsk': 0.0, 'Rku': 1.8, 'Rz': 2 * a},
        ),
        'square': (lambda u: a if u < 0.5 else -a, {'Ra': a, 'Rq': a, 'Rsk': 0.0, 'Rku': 1.0, 'Rz': 2 * a}),
    }


def numeric(z) -> dict:
    values = [z((i + 0.5) / SAMPLES) for i in range(SAMPLES)]
    mean = sum(values) / SAMPLES
    dev = [v - mean for v in values]
    ra = sum(abs(v) for v in dev) / SAMPLES
    rq = math.sqrt(sum(v * v for v in dev) / SAMPLES)
    rsk = sum(v ** 3 for v in dev) / SAMPLES / rq ** 3
    rku = sum(v ** 4 for v in dev) / SAMPLES / rq ** 4
    return {'Ra': ra, 'Rq': rq, 'Rsk': rsk, 'Rku': rku, 'Rz': max(dev) - min(dev)}


def main() -> None:
    cases = []
    for amplitude_um in (0.8, 1.6):
        for name, (z, closed) in profiles(amplitude_um).items():
            num = numeric(z)
            worst = max(abs(num[k] - closed[k]) for k in closed)
            assert worst < 1e-3 * amplitude_um, (name, worst)
            cases.append({
                'id': f'ST-{name}-{amplitude_um}',
                'profile': name,
                'amplitudeUm': amplitude_um,
                'expected': {k: round(v, 9) for k, v in closed.items()},
                'numericCheckMaxAbsError': round(worst, 12),
                'tolerance': {'abs': 1e-4, 'unit': 'um (Rsk, Rku dimensionless)'},
            })
    out = {'$comment': 'Generated by generate_surface_texture_reference.py; closed forms in its docstring. Do not edit.', 'cases': cases}
    with open(os.path.join(HERE, 'surface_texture_reference.json'), 'w', encoding='utf-8') as handle:
        json.dump(out, handle, indent=1)
        handle.write('\n')
    print(f'wrote {len(cases)} cases')


if __name__ == '__main__':
    main()
